import { z } from "zod";

/**
 * Design studio (feature `designStudio`, docs/features/design-studio). The shared contract
 * between `openwork-server` and the app: both sides import these schemas.
 *
 * A design lives as plain files inside its project folder, so the agent edits it with its normal
 * file tools, it travels in the `.owapp` export and task review can accept/discard its changes:
 *
 *   <project>/proyecto/diseno/<designId>/
 *     design.json        manifest (designManifestSchema)
 *     pages/<pageId>.html one self-contained HTML document per page/slide/screen
 *     styles.css         optional shared stylesheet, referenced by pages as "../styles.css"
 *     assets/...         images, logos, SVG illustrations (referenced as "../assets/<file>")
 *     thumbnail.png      optional preview of the first page
 *     board.json         only for kind "board" (boardSchema)
 *     tokens.json        only for kind "system" (designTokensSchema)
 *
 * Pages are rendered in a sandboxed iframe with no network access: every reference must be
 * relative to the design folder. Everything here is local; no external service is involved.
 */

export const DESIGN_KINDS = ["slides", "mockup", "system", "board"] as const;
export const designKindSchema = z.enum(DESIGN_KINDS);
export type DesignKind = z.infer<typeof designKindSchema>;

export const DESIGN_EXPORT_FORMATS = ["pdf", "pptx", "png", "html"] as const;
export const designExportFormatSchema = z.enum(DESIGN_EXPORT_FORMATS);
export type DesignExportFormat = z.infer<typeof designExportFormatSchema>;

/** Every limit in one place: the server enforces them, the UI shows them. */
export const DESIGN_LIMITS = {
  titleChars: 120,
  pages: 200,
  /** One page document. */
  pageBytes: 2 * 1024 * 1024,
  /** One asset file. */
  assetBytes: 20 * 1024 * 1024,
  /** Everything in one design folder. */
  designBytes: 200 * 1024 * 1024,
  designsPerProject: 500,
  boardElements: 5_000,
} as const;

/** Page sizes by kind, in CSS pixels. Slides are 16:9. */
export const DESIGN_PAGE_SIZES = {
  slides: { width: 1920, height: 1080 },
  mockup: { width: 1440, height: 900 },
  system: { width: 1440, height: 900 },
  board: { width: 4000, height: 3000 },
} as const satisfies Record<DesignKind, { width: number; height: number }>;

/** Ids are generated by the server; they never carry a path. */
export const designIdSchema = z.string().regex(/^[a-z0-9][a-z0-9-]{0,63}$/);
export const pageIdSchema = z.string().regex(/^[a-z0-9][a-z0-9-]{0,63}$/);

/** A path inside a design folder: relative, forward slashes, no "..", no hidden segments. */
export const designRelativePathSchema = z.string().min(1).max(240).refine(
  value => !value.startsWith("/") && !value.includes("\\") && value.split("/").every(part => part !== "" && part !== "." && part !== ".." && !part.startsWith(".")),
  "La ruta debe ser relativa a la carpeta del diseño.",
);

export const designPageSchema = z.object({
  id: pageIdSchema,
  title: z.string().max(DESIGN_LIMITS.titleChars),
  /** Relative path of the page document, e.g. "pages/p-1.html". */
  file: designRelativePathSchema,
  width: z.number().int().positive().max(20_000),
  height: z.number().int().positive().max(20_000),
  /** Speaker notes (slides) or a short description (screens). */
  notes: z.string().max(10_000).optional(),
});
export type DesignPage = z.infer<typeof designPageSchema>;

export const designManifestSchema = z.object({
  format: z.literal("openwork.design"),
  version: z.literal(1),
  id: designIdSchema,
  kind: designKindSchema,
  title: z.string().min(1).max(DESIGN_LIMITS.titleChars),
  createdAt: z.number().int(),
  updatedAt: z.number().int(),
  /** Ordered. A board keeps its single canvas page here too. */
  pages: z.array(designPageSchema).max(DESIGN_LIMITS.pages),
  /** Id of the design system (a design of kind "system" in the same project) this design follows. */
  systemId: designIdSchema.nullable().default(null),
  /** Relative path of the preview image, when one was captured. */
  thumbnail: designRelativePathSchema.nullable().default(null),
});
export type DesignManifest = z.infer<typeof designManifestSchema>;

/** One row of the gallery: a design and the project it belongs to. */
export const designSummarySchema = z.object({
  workspaceId: z.string().min(1),
  projectName: z.string(),
  id: designIdSchema,
  kind: designKindSchema,
  title: z.string(),
  pages: z.number().int().nonnegative(),
  updatedAt: z.number().int(),
  createdAt: z.number().int(),
  hasThumbnail: z.boolean(),
});
export type DesignSummary = z.infer<typeof designSummarySchema>;

// ---- Design system (kind "system"): tokens.json ----

const tokenName = z.string().min(1).max(80);
export const designTokensSchema = z.object({
  format: z.literal("openwork.design-tokens"),
  version: z.literal(1),
  /** One paragraph shown in Overview and handed to the agent as brand context. */
  overview: z.string().max(20_000).default(""),
  /** Writing rules for copy (voice, tone, formats). Handed to the agent as context. */
  content: z.string().max(20_000).default(""),
  colors: z.array(z.object({ name: tokenName, value: z.string().max(64), role: z.string().max(80).optional(), group: z.string().max(80).optional() })).default([]),
  typography: z.array(z.object({ name: tokenName, family: z.string().max(200), size: z.string().max(32), weight: z.union([z.number(), z.string().max(16)]), lineHeight: z.string().max(32).optional(), sample: z.string().max(200).optional() })).default([]),
  spacing: z.array(z.object({ name: tokenName, value: z.string().max(32) })).default([]),
  radii: z.array(z.object({ name: tokenName, value: z.string().max(32) })).default([]),
  shadows: z.array(z.object({ name: tokenName, value: z.string().max(400) })).default([]),
  gradients: z.array(z.object({ name: tokenName, value: z.string().max(400) })).default([]),
  layout: z.array(z.object({ name: tokenName, value: z.string().max(200), note: z.string().max(400).optional() })).default([]),
  /** Component previews: each is a page document of the design (relative path). */
  components: z.array(z.object({ name: tokenName, file: designRelativePathSchema, description: z.string().max(2_000).optional() })).default([]),
  /** Brand assets (logos, icons, illustrations) inside the design folder. */
  assets: z.array(z.object({ name: tokenName, file: designRelativePathSchema })).default([]),
});
export type DesignTokens = z.infer<typeof designTokensSchema>;

// ---- Board (kind "board"): board.json ----

const boardStyleSchema = z.object({
  fill: z.string().max(64).optional(),
  stroke: z.string().max(64).optional(),
  strokeWidth: z.number().min(0).max(64).optional(),
  color: z.string().max(64).optional(),
  fontSize: z.number().min(4).max(400).optional(),
  opacity: z.number().min(0).max(1).optional(),
});
const boardBase = {
  id: z.string().min(1).max(64),
  x: z.number(),
  y: z.number(),
  width: z.number().min(0),
  height: z.number().min(0),
  rotation: z.number().default(0),
  style: boardStyleSchema.default({}),
  /** Id of the frame that contains it, if any. */
  frameId: z.string().max(64).nullable().default(null),
};
export const boardElementSchema = z.discriminatedUnion("type", [
  z.object({ ...boardBase, type: z.literal("frame"), title: z.string().max(DESIGN_LIMITS.titleChars) }),
  z.object({ ...boardBase, type: z.literal("rect") }),
  z.object({ ...boardBase, type: z.literal("ellipse") }),
  z.object({ ...boardBase, type: z.literal("text"), text: z.string().max(10_000) }),
  z.object({ ...boardBase, type: z.literal("sticky"), text: z.string().max(10_000) }),
  z.object({ ...boardBase, type: z.literal("path"), points: z.array(z.tuple([z.number(), z.number()])).max(5_000) }),
  /** An image or SVG illustration from the design's assets. */
  z.object({ ...boardBase, type: z.literal("image"), src: designRelativePathSchema }),
]);
export type BoardElement = z.infer<typeof boardElementSchema>;

export const boardSchema = z.object({
  format: z.literal("openwork.board"),
  version: z.literal(1),
  elements: z.array(boardElementSchema).max(DESIGN_LIMITS.boardElements),
  viewport: z.object({ x: z.number(), y: z.number(), zoom: z.number().min(0.05).max(8) }).default({ x: 0, y: 0, zoom: 1 }),
});
export type Board = z.infer<typeof boardSchema>;
